-- Execute apenas se ainda nao criou a tabela.
create table if not exists public.medicoes (
  id bigint generated by default as identity primary key,
  dispositivo text not null default 'ESP32-AlagaSave',
  distancia_cm numeric,
  nivel_agua_cm numeric,
  nivel_agua_percentual numeric,
  chuva_adc integer,
  chuva_percentual numeric,
  situacao_chuva text,
  status_nivel text,
  data_hora timestamptz not null default now()
);

alter table public.medicoes enable row level security;

drop policy if exists "Permitir leitura publica demonstracao" on public.medicoes;
create policy "Permitir leitura publica demonstracao"
on public.medicoes for select to anon, authenticated using (true);

drop policy if exists "Permitir insercao publica demonstracao" on public.medicoes;
create policy "Permitir insercao publica demonstracao"
on public.medicoes for insert to anon, authenticated with check (true);
